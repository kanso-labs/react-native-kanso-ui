#!/usr/bin/env node
// Writes src/tokens/defaults.ts from kanso-ui's token source, the DTCG file the
// pinned `@kanso-labs/kanso-ui` publishes as `./tokens.json`. That file is the
// only place this repository takes a token value from (see AGENTS.md), and this
// script is the only thing that reads it.
//
// The module it writes holds every `--kui-*` property in its light and its dark
// value, each in CSS syntax exactly as kanso-ui's tokens.css declares it, so
// one theme map serves both libraries and src/theme/resolve.ts reads both the
// same way. It also holds the KuiTheme type, generated the way kanso-ui
// generates its own, and the window size class breakpoints, which neither
// library offers as a property to override.
//
// The output is not committed. A Renovate bump of `@kanso-labs/kanso-ui` then
// carries a token change on its own, where a committed copy would go stale
// with the bump and fail the tests that compare it with the new tokens.css.
// `build`, `lint` and `test` run this first, and nothing else writes the file.
//
// Run directly (`npm run tokens:build`), or import registerFormats and
// styleDictionaryConfig to drive the same build through Style Dictionary.
import { createRequire } from 'node:module'
import StyleDictionary from 'style-dictionary'

/**
 * @typedef {import('style-dictionary/types').TransformedToken} TransformedToken
 * @typedef {{ dark: string, light: string }} Declaration
 */

const require = createRequire(import.meta.url)

const BANNER = `// AUTO-GENERATED by scripts/build-tokens.mjs from @kanso-labs/kanso-ui/tokens.json.
// Not committed and not to be edited: \`npm run tokens:build\` writes it.

`

// The segment each token group takes in a property's name, as in kanso-ui:
// `radii.component.sm` is `--kui-radius-sm`. A group is read from its
// `component` family where it has one, the primitives behind it being values
// the components reach only through it.
const GROUPS = new Map([
  ['radii', 'radius'],
  ['sizing', 'sizing'],
  ['spacing', 'spacing'],
])

// Style Dictionary silently replaces a format registered again under the same
// name, so calling this more than once per process is safe.
export function registerFormats() {
  StyleDictionary.registerFormat({
    /** @param {import('style-dictionary/types').FormatFnArguments} args */
    format: ({ dictionary }) => defaultsSource(dictionary.allTokens),
    name: 'ts/token-defaults',
  })
}

/** @param {TransformedToken[]} allTokens @returns {[string, number][]} */
function breakpoints(allTokens) {
  return allTokens
    .filter((t) => t.path[0] === 'layout' && t.path[1] === 'breakpoint')
    .map((token) => [token.path[2] ?? '', pixels(token)])
}

/** @param {TransformedToken} token @returns {string} */
function cubicBezier(token) {
  /** @type {unknown} */
  const value = token.$value
  if (
    !Array.isArray(value) ||
    value.length !== 4 ||
    !value.every((v) => typeof v === 'number')
  ) {
    throw new TypeError(`Expected four numbers for ${token.path.join('.')}`)
  }
  return `cubic-bezier(${value.join(', ')})`
}

// The property a token declares and its value, or undefined for a token that
// is not part of the override contract.
/** @param {TransformedToken} token @returns {[string, string] | undefined} */
function declaration(token) {
  const [group, family, key, field] = token.path
  if (!group || !family) return undefined
  if (group === 'typography' && key) {
    if (family === 'fontFamily') {
      return [
        `--kui-typography-font-family-${kebabCase(key)}`,
        fontStack(token),
      ]
    }
    if (family === 'fontWeight') {
      return [`--kui-typography-weight-${kebabCase(key)}`, String(token.$value)]
    }
    if (family === 'scale' && field) {
      const value = field === 'font' ? fontStack(token) : String(token.$value)
      return [
        `--kui-typography-${kebabCase(key)}-${kebabCase(field)}`,
        field === 'font' || field === 'weight'
          ? throughAlias(token, value)
          : value,
      ]
    }
  }
  if (group === 'motion' && key) {
    if (family === 'duration') {
      return [`--kui-motion-duration-${kebabCase(key)}`, String(token.$value)]
    }
    if (family === 'easing') {
      return [`--kui-motion-easing-${kebabCase(key)}`, cubicBezier(token)]
    }
  }
  if (group === 'shadow') {
    return [`--kui-shadow-elevation${family}`, shadowLayers(token)]
  }
  if (group === 'stateLayerOpacity') {
    return [
      `--kui-state-layer-opacity-${kebabCase(family)}`,
      String(token.$value),
    ]
  }
  const segment = GROUPS.get(group)
  if (segment && family === 'component' && key) {
    return [`--kui-${segment}-${kebabCase(key)}`, String(token.$value)]
  }
  return undefined
}

/** @param {TransformedToken[]} allTokens @returns {Map<string, Declaration>} */
function declarations(allTokens) {
  /** @type {Map<string, Declaration>} */
  const properties = new Map()
  /** @type {Map<string, string>} */
  const dark = new Map()
  for (const token of allTokens) {
    const [group, scheme, key] = token.path
    if (group === 'semantic' && key) {
      const property = `--kui-color-${kebabCase(key)}`
      if (scheme === 'dark') dark.set(property, String(token.$value))
      else if (scheme === 'light') {
        properties.set(property, {
          dark: '',
          light: String(token.$value),
        })
      }
      continue
    }
    const found = declaration(token)
    if (found) properties.set(found[0], { dark: found[1], light: found[1] })
  }
  for (const [property, value] of properties) {
    if (!property.startsWith('--kui-color-')) continue
    const darkValue = dark.get(property)
    if (darkValue === undefined) {
      throw new TypeError(`semantic.dark has no value for ${property}`)
    }
    value.dark = darkValue
  }
  return new Map(
    [...properties].toSorted(([a], [b]) =>
      a.localeCompare(b, 'en', { numeric: true }),
    ),
  )
}

/** @param {TransformedToken[]} allTokens @returns {string} */
function defaultsSource(allTokens) {
  const properties = declarations(allTokens)
  const type = [...properties]
    .map(([name, { dark, light }]) => {
      const value =
        light === dark
          ? `Defaults to \`${light}\`.`
          : `Defaults to \`${light}\` in the light scheme and \`${dark}\` in the dark.`
      return `  /** ${value} */\n  readonly '${name}'?: string`
    })
    .join('\n')
  const bounds = breakpoints(allTokens)
    .map(([name, value]) => `  ${name}: ${value},`)
    .join('\n')
  return `${BANNER}/**
 * A theme: any of the \`--kui-*\` custom properties \`tokens.css\` lists, each set
 * to a value in CSS syntax. Hand one to \`ThemeScope\`'s \`theme\` prop, and every
 * component inside reads it.
 *
 * The values hold for both schemes. A theme with a value of its own for light
 * and for dark is two of these, with the scope handed the one for the scheme
 * in use.
 */
type KuiTheme = {
${type}
}

/** Every property at its value in the light scheme. */
const light: Required<KuiTheme> = {
${themeBlock(properties, 'light')}
}

/** Every property at its value in the dark scheme. */
const dark: Required<KuiTheme> = {
${themeBlock(properties, 'dark')}
}

/**
 * The lower bound of each window size class, in dp. A media query cannot read
 * a custom property, so on web these are compiled in rather than overridable,
 * and they are constants here for the same contract.
 */
const breakpoints = {
${bounds}
} as const

export { breakpoints, dark, light }
export type { KuiTheme }
`
}

/** @param {TransformedToken} token @returns {string} */
function fontStack(token) {
  /** @type {unknown} */
  const value = token.$value
  if (!isStringArray(value)) {
    throw new TypeError(`Expected string[] for ${token.path.join('.')}`)
  }
  return value
    .map((family) => (family.includes(' ') ? `'${family}'` : family))
    .join(', ')
}

/** @param {unknown} value @returns {value is string[]} */
function isStringArray(value) {
  return Array.isArray(value) && value.every((v) => typeof v === 'string')
}

/** @param {string} key @returns {string} */
function kebabCase(key) {
  return key.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)
}

/** @param {TransformedToken} token @returns {number} */
function pixels(token) {
  const match = /^(\d+(?:\.\d+)?)px$/u.exec(String(token.$value))
  if (!match) {
    throw new TypeError(`Expected a length in px for ${token.path.join('.')}`)
  }
  return Number(match[1])
}

/** @param {TransformedToken} token @returns {string} */
function shadowLayers(token) {
  /** @type {unknown} */
  const value = token.$value
  if (!Array.isArray(value)) {
    throw new TypeError(`Expected shadow layers for ${token.path.join('.')}`)
  }
  return value
    .map((/** @type {Record<string, string>} */ layer) =>
      ['offsetX', 'offsetY', 'blur', 'spread', 'color']
        .map((field) => {
          const part = layer[field]
          if (typeof part !== 'string') {
            throw new TypeError(
              `Expected ${field} in every layer of ${token.path.join('.')}`,
            )
          }
          return part
        })
        .join(' '),
    )
    .join(', ')
}

/** @param {Map<string, Declaration>} properties @param {'dark' | 'light'} scheme @returns {string} */
function themeBlock(properties, scheme) {
  return [...properties]
    .map(
      ([name, value]) =>
        `  ${JSON.stringify(name)}: ${JSON.stringify(value[scheme])},`,
    )
    .join('\n')
}

// A type role's font and weight alias a typeface and a weight, and kanso-ui
// keeps the alias in the value: the role's own property falls back to the
// typeface's property, then to the literal. Overriding
// `--kui-typography-font-family-brand` then reaches every role that uses it.
/** @param {TransformedToken} token @param {string} value @returns {string} */
function throughAlias(token, value) {
  /** @type {unknown} */
  const original = token.original.$value
  const match =
    typeof original === 'string'
      ? /^\{typography\.(fontFamily|fontWeight)\.(\w+)\}$/u.exec(original)
      : null
  if (!match?.[1] || !match[2]) return value
  const segment = match[1] === 'fontFamily' ? 'font-family' : 'weight'
  return `var(--kui-typography-${segment}-${kebabCase(match[2])}, ${value})`
}

export const styleDictionaryConfig = {
  log: { verbosity: /** @type {const} */ ('silent') },
  platforms: {
    ts: {
      buildPath: 'src/tokens/',
      files: [{ destination: 'defaults.ts', format: 'ts/token-defaults' }],
      // The format keys off `token.path`, not `token.name`. This only gives
      // every token a distinct name, so Style Dictionary's collision warnings,
      // aimed at formats that use the flat name, stay quiet.
      transforms: ['name/kebab'],
    },
  },
  source: [require.resolve('@kanso-labs/kanso-ui/tokens.json')],
  usesDtcg: true,
}

if (import.meta.main) {
  registerFormats()
  const sd = new StyleDictionary(styleDictionaryConfig)
  await sd.buildAllPlatforms()
}
