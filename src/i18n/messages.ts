// The words the library writes itself: the pending ring's name, a bottom
// sheet's drag handle, a collection's loading-more and empty rows, what
// selecting a list's row is called, what a Select shows while nothing is
// chosen, the names of a ComboBox's list and the button opening it, how many
// rows a search leaves, a calendar's, a date's segments, a field's character
// limit, CopyField's button, the names of SearchField's clear button, a
// SearchView's back button, Snackbar's close button, a chip's remove button,
// NumberField's steppers and what opening and closing a tree's row is called.
// Each one a call site might want in other words stands behind a prop that
// names it otherwise: `pendingLabel` for the ring, `aria-label` for the
// handle, `label` for the loading-more row, `renderEmptyState` for the empty
// one, `selectLabel` for the selection, `placeholder` for a Select's empty
// value, `characterLimitLabel` for the limit, `copyLabel` and `copiedLabel`
// for CopyField, `clearLabel`, `backLabel`, `closeLabel` and `removeLabel` for
// the four buttons, and `decrementLabel` and `incrementLabel` for the
// steppers.
//
// Copied from kanso-ui's src/i18n/messages.ts, one entry per locale React Aria
// ships, and kept in step with it by hand: the web library publishes no copy of
// its table, and a word that differs between the two would name the same ring
// two ways. The handle's name is this table's alone, since web's sheet draws
// its handle as decoration and names nothing. `select` is React Aria's own word
// for a grid list row's checkbox, which web's List takes from React Aria's
// tables rather than its own, copied here so the two read the same, and
// `selectPlaceholder` is what React Aria's Select, and so web's, shows while
// nothing is chosen. `results` is React Aria's too, the count its ComboBox
// announces, which Autocomplete and ComboBox announce as a search narrows a
// list, and `showSuggestions` and `suggestions` are the names its ComboBox
// gives the button that opens the list and the list itself. `calendar` is React
// Aria's calendar dictionary, which web's Calendar reads, beside the names of
// the month and year fields that web reads from the browser's
// `Intl.DisplayNames` and Hermes lacks, written here from the same CLDR data.
// `segments` is the same: the name of each part of a date, which web's date
// field reads from `Intl.DisplayNames` too, beside the description of the date
// it holds, from React Aria's date picker dictionary, and what an empty one
// reads as, from its spin button dictionary. `clearSearch`, `close`,
// `decrease`, `increase` and `remove` are React Aria's as well, from the
// search field, toast, number field and tag dictionaries its own controls name
// those buttons from on web, and `collapse` and `expand` from its tree
// dictionary, which names web's Tree chevron. The others were drafted for
// kanso-ui's table rather than taken from a translation service, and each one
// wants a native speaker's eye before it is trusted; a call site can always
// pass its own words through the prop.

type LibraryMessages = {
  /** What a SearchView's back button is called. */
  readonly back: string
  /**
   * The words a calendar writes: its two chevrons, the names its dates
   * take, where `{date}` is the date written out in full, and the fields
   * its month and year menus are named by.
   */
  readonly calendar: {
    /** A date the calendar holds. */
    readonly dateSelected: string
    /** Added after the latest date `maxValue` allows. */
    readonly maximumDate: string
    /** Added after the earliest date `minValue` allows. */
    readonly minimumDate: string
    /** What the month is called, after the month a menu button shows. */
    readonly month: string
    /** The chevron that moves to the next month. */
    readonly next: string
    /** The chevron that moves to the previous month. */
    readonly previous: string
    /** Today, when the calendar does not hold it. */
    readonly todayDate: string
    /** Today, when the calendar holds it. */
    readonly todayDateSelected: string
    /** What the year is called, after the year a menu button shows. */
    readonly year: string
  }
  /**
   * What a field's character limit says, for a screen reader, in the plural
   * forms the locale's rules give it; `{count}` is the limit.
   */
  readonly characterLimit: PluralForms
  /** What SearchField's clear button is called. */
  readonly clearSearch: string
  /** What Snackbar's close button is called. */
  readonly close: string
  /** What closing a tree's open row is called, for a screen reader. */
  readonly collapse: string
  /** What CopyField's button says, and announces, once it has copied. */
  readonly copied: string
  /** What CopyField's button says. */
  readonly copy: string
  /**
   * What NumberField's stepper that lowers the value is called; `{label}`
   * is the field's label.
   */
  readonly decrease: string
  /** What a bottom sheet's handle is called, where it is a control. */
  readonly dragHandle: string
  /** What opening a tree's closed row is called, for a screen reader. */
  readonly expand: string
  /**
   * What NumberField's stepper that raises the value is called; `{label}`
   * is the field's label.
   */
  readonly increase: string
  /** What a pending button's ring is called. */
  readonly loading: string
  /** What a collection's row says while more items are on their way. */
  readonly loadingMore: string
  /** What a collection with nothing in it says. */
  readonly noResults: string
  /**
   * What a removable chip's remove button is called, before the chip's own
   * text.
   */
  readonly remove: string
  /**
   * How many rows a search leaves, for a screen reader, in the plural
   * forms React Aria's table gives the locale; `{count}` is the number.
   */
  readonly results: {
    readonly one: string
    readonly other: string
  }
  /**
   * What a date's segments are called, each one named for a screen reader
   * before the field's label, and what describes the date or the time a
   * field holds, where `{date}` is the date written out.
   */
  readonly segments: {
    readonly day: string
    readonly dayPeriod: string
    /** What a segment with nothing in it reads as, for a screen reader. */
    readonly empty: string
    readonly era: string
    readonly hour: string
    readonly minute: string
    readonly month: string
    readonly second: string
    /** The date a field holds, read after its segments. */
    readonly selectedDate: string
    /** The time a field holds, where `{time}` is the time written out. */
    readonly selectedTime: string
    readonly timeZoneName: string
    readonly year: string
  }
  /** What selecting a list's row is called, beside its checkbox. */
  readonly select: string
  /** What a Select shows while nothing is chosen. */
  readonly selectPlaceholder: string
  /** What the button opening a ComboBox's list is called, before its label. */
  readonly showSuggestions: string
  /** What a ComboBox's list is called, before the field's label. */
  readonly suggestions: string
}

/**
 * A message in each plural form the locale's rules give it, where `other`
 * always stands in for a form the locale's entry leaves out.
 */
type PluralForms = Partial<Record<Intl.LDMLPluralRule, string>> & {
  readonly other: string
}

